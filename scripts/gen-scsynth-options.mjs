/*
 * gen-scsynth-options.mjs — js/lib/scsynth_options_schema.js from
 * dsp/scsynth/scsynth_options.h.
 *
 * The guest's options are listed ONCE, in the C header's SCSYNTH_OPTIONS
 * X-macro. The JavaScript client needs the same list for its defaults, its
 * validation and its encoder, and a browser cannot read a C header — so this
 * script writes the list out as a module, which is committed so that an npm
 * consumer needs no build step. test/scsynth_options_schema.spec.mjs fails
 * when the committed module and the header disagree.
 *
 *   node scripts/gen-scsynth-options.mjs          # write the module
 *   node scripts/gen-scsynth-options.mjs --check  # exit 1 if it is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const HEADER = join(ROOT, "dsp/scsynth/scsynth_options.h");
const MODULE = join(ROOT, "js/lib/scsynth_options_schema.js");

export function parseHeader(src) {
  const macro = src.match(/#define SCSYNTH_OPTIONS\(X\)([\s\S]*?)\n\n/);
  if (!macro) throw new Error(`${HEADER}: no SCSYNTH_OPTIONS(X) macro`);
  const re = /X\(\s*(\w+)\s*,\s*('.'|0)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)/g;
  const out = [];
  for (const m of macro[1].matchAll(re)) {
    out.push({
      name: m[1],
      flag: m[2] === "0" ? null : m[2].slice(1, 2),
      default: Number(m[3]),
      min: Number(m[4]),
      max: Number(m[5]),
      doc: m[6].replace(/\\"/g, '"'),
    });
  }
  if (out.length === 0) throw new Error(`${HEADER}: the macro lists no options`);
  return out;
}

// SCSYNTH_HEAP_HEADROOM_BYTES: what every host adds to the real-time pool when
// it sizes the heap scsynth allocates from (scsynth_heap_bytes in the header).
export function parseHeapHeadroom(src) {
  const m = src.match(/#define SCSYNTH_HEAP_HEADROOM_BYTES\s+(\d+)u?\b/);
  if (!m) throw new Error(`${HEADER}: no SCSYNTH_HEAP_HEADROOM_BYTES literal`);
  return Number(m[1]);
}

export function render(options, heapHeadroom) {
  const lines = options.map((o) =>
    `  { name: ${JSON.stringify(o.name)}, flag: ${JSON.stringify(o.flag)}, ` +
    `default: ${o.default}, min: ${o.min}, max: ${o.max}, doc: ${JSON.stringify(o.doc)} },`);
  return `// GENERATED by scripts/gen-scsynth-options.mjs from dsp/scsynth/scsynth_options.h.
// Do not edit: change the header and regenerate. test/scsynth_options_schema.spec.mjs
// fails when this file and the header disagree.
//
// The options scsynth takes from a host: name, the scsynth command-line
// letter, default, range and a line of documentation. The client's defaults,
// validation and the "name=value" block it sends all come from here.
export const scsynthOptionSchema = Object.freeze([
${lines.join("\n")}
]);
export default scsynthOptionSchema;

// What a host adds to the real-time pool (realTimeMemorySize KB) when it sizes
// the heap scsynth allocates from — SCSYNTH_HEAP_HEADROOM_BYTES.
export const scsynthHeapHeadroomBytes = ${heapHeadroom};
`;
}

const main = () => {
  const src = readFileSync(HEADER, "utf8");
  const text = render(parseHeader(src), parseHeapHeadroom(src));
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(MODULE, "utf8"); } catch {}
    if (current !== text) {
      console.error(`${MODULE} is stale: run node scripts/gen-scsynth-options.mjs`);
      process.exit(1);
    }
    return;
  }
  writeFileSync(MODULE, text);
  console.log(`wrote ${MODULE}`);
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
